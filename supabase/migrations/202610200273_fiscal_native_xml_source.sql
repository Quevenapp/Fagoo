-- 273 (notas fiscais lane, wave F): what "Validar" (Outras opções de NF-e) and "Gerar XML (suporte)" (⋮ da NFC-e) need to build the
-- native XML of a note of the Brufap in the Worker: the saved note (the same envelope as erp_fiscal_invoice_get), the company identity
-- (016) with the extra data of Alterar dados da empresa (151: Tipo da Pessoa, Isento, Inscrição Municipal, CNAE, Suframa and the
-- Inscrições Estaduais dos substitutos tributários), the confirmed regime and the next number of the homologation series of the note.
-- Read only: nothing is reserved, numbered, signed, transmitted or stored; the series keeps its next number. Notes registered from a
-- third party or imported from an XML (T, S, X) are not generated by the Brufap and are refused, like deleted notes.
-- Requires 016, 046, 112, 143 and 151. No function of another lane is replaced.
begin;

do $$ begin
  if to_regprocedure('erp_fiscal_invoices.invoice_record(uuid)') is null or to_regprocedure('erp_fiscal_invoices.invoice_envelope(jsonb,text)') is null
    or to_regprocedure('erp_fiscal_invoices.require_write(uuid)') is null or to_regclass('erp_company.identity') is null or to_regclass('erp_company.extra') is null then
    raise exception 'fiscal_native_xml_273_requires_016_112_143_151' using errcode='55000'; end if;
end $$;

-- Text of the identity or extra data, trimmed; null when absent or empty.
create function erp_fiscal_invoices.company_text(p jsonb,p_key text,p_max integer) returns text language sql immutable set search_path=pg_catalog as $$
  select case when jsonb_typeof(p->p_key)='string' and btrim(p->>p_key)<>'' then left(btrim(p->>p_key),p_max) end;
$$;

create function public.erp_fiscal_invoice_xml_source(p_user_id uuid,p_id uuid) returns jsonb language plpgsql stable security definer set search_path=pg_catalog as $$
declare role text:=erp_fiscal_invoices.require_write(p_user_id);v erp_fiscal_invoices.invoice%rowtype;r jsonb;i jsonb;x jsonb;crt text;document text;numbering jsonb;
begin
  if p_id is null then raise exception 'erp_fiscal_query_invalid' using errcode='22023'; end if;
  select * into v from erp_fiscal_invoices.invoice where id=p_id;
  if not found then raise exception 'erp_fiscal_invoice_not_found' using errcode='P0002'; end if;
  if v.deleted_at is not null or v.issue_type in('T','S','X') then raise exception 'erp_fiscal_invoice_native_xml_unavailable' using errcode='22023'; end if;
  r:=erp_fiscal_invoices.invoice_record(p_id);
  select data into i from erp_company.identity where singleton;
  select data into x from erp_company.extra where singleton;
  select f.crt into crt from erp_company.fiscal f where f.singleton;
  i:=coalesce(i,'{}'::jsonb);x:=coalesce(x,'{}'::jsonb);
  document:=nullif(regexp_replace(coalesce(i->>'cnpj',''),'[^0-9]','','g'),'');
  -- The homologation series of the note (046); the one of the company CNPJ first. Only read: the next number is a prediction.
  if to_regclass('erp_fiscal_numbering.series') is not null then
    execute 'select jsonb_build_object(''series'',s.series,''next_number'',s.next_number,''enabled'',s.enabled) from erp_fiscal_numbering.series s
      where s.model=$1 and s.environment=''2'' and s.series=$2 order by (s.issuer_cnpj=$3) desc,s.created_at limit 1' into numbering using v.model,v.series,coalesce(document,'');
  end if;
  return jsonb_build_object('envelope',erp_fiscal_invoices.invoice_envelope(r,role),
    'emitter',jsonb_build_object('legal_name',erp_fiscal_invoices.company_text(i,'legal_name',200),'trade_name',erp_fiscal_invoices.company_text(i,'trade_name',200),
      'document',document,'person_type',case when x->>'person_type'='fisica' then 'fisica' else 'juridica' end,
      'ie',erp_fiscal_invoices.company_text(i,'ie',30),'ie_exempt',coalesce(x->'ie_exempt'='true'::jsonb,false),
      'municipal_registration',erp_fiscal_invoices.company_text(x,'municipal_registration',30),'cnae',erp_fiscal_invoices.company_text(x,'cnae',9),
      'suframa',erp_fiscal_invoices.company_text(x,'suframa',12),
      'substitute_ies',case when jsonb_typeof(x->'substitute_ies')='array' then x->'substitute_ies' else '[]'::jsonb end,
      'crt',crt,'regime_confirmed',crt is not null,
      'address',jsonb_build_object('street',erp_fiscal_invoices.company_text(i,'street',200),'number',erp_fiscal_invoices.company_text(i,'number',30),
        'complement',erp_fiscal_invoices.company_text(i,'complement',200),'district',erp_fiscal_invoices.company_text(i,'district',100),
        'city',erp_fiscal_invoices.company_text(i,'city',100),'municipality_code',erp_fiscal_invoices.company_text(i,'municipality_code',7),
        'state',erp_fiscal_invoices.company_text(i,'state',2),'postal_code',erp_fiscal_invoices.company_text(i,'postal_code',9),'phone',erp_fiscal_invoices.company_text(i,'phone',40))),
    'numbering',coalesce(numbering,jsonb_build_object('series',v.series,'next_number',null,'enabled',null)),
    'data_mode','erp_native_homologation');
end $$;

revoke all on function erp_fiscal_invoices.company_text(jsonb,text,integer) from public,anon,authenticated,service_role;
revoke all on function public.erp_fiscal_invoice_xml_source(uuid,uuid) from public,anon,authenticated;
grant execute on function public.erp_fiscal_invoice_xml_source(uuid,uuid) to service_role;
commit;
