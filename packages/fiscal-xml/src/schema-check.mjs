/**
 * NF-e / NFC-e 4.00 against the official layout of PL 010f v1.04, without Python, network or XSD files at run time: the grammar is
 * compiled from the hash-pinned XSDs by tools/fiscal/compile-nfe-schema.mjs (nfe-schema-pl010f.mjs). Runs in the Worker and in the
 * browser (@xmldom/xmldom only, no Node built-ins). Two uses:
 *  - checkNfeSchema(xml): the structure (order, presence, repetitions, namespaces, attributes) and every value (patterns, enumerations,
 *    lengths) of an NFe document, like the XSD validator. The xmldsig Signature is not checked here: it is optional with
 *    { signature: 'optional' } (the XML generated by the Fagoo is not signed) and required otherwise.
 *  - schemaXml(tree): writes an NFe document from a plain object tree in the order of the layout, so the generator never depends on
 *    a hand-written element order. Unknown names throw; values are escaped text.
 * A valid result means only that the bytes follow the layout: it is not a tax, signature, authorization or SEFAZ rule check.
 */
import { DOMParser } from '@xmldom/xmldom';
import grammar from './nfe-schema-pl010f.mjs';

export const SCHEMA_PROFILE = grammar.profile;
export const NFE_NS = grammar.namespace;
const DS = 'http://www.w3.org/2000/09/xmldsig#';
export const SCHEMA_MAX_BYTES = 512000;
const MAX_ERRORS = 100;
export class SchemaError extends Error { constructor(code) { super(code); this.code = code; } }

// ---------------- grammar helpers ----------------
const firstCache = new WeakMap();
function first(p, unsigned) {
  const key = unsigned ? 'u' : 's', cached = firstCache.get(p)?.[key];
  if (cached) return cached;
  let out;
  if (p[0] === 'e') out = { names: new Set([p[1]]), nullable: p[3] === 0 || (unsigned && p[2] === '#sig') };
  else {
    const [k, min, , items] = p, names = new Set();
    let nullable;
    if (k === 's') {
      let all = true;
      for (const item of items) { const f = first(item, unsigned); f.names.forEach(n => names.add(n)); if (!f.nullable) { all = false; break; } }
      nullable = min === 0 || all;
    } else {
      let any = false;
      for (const item of items) { const f = first(item, unsigned); f.names.forEach(n => names.add(n)); any ||= f.nullable; }
      nullable = min === 0 || any;
    }
    out = { names, nullable };
  }
  firstCache.set(p, { ...(firstCache.get(p) ?? {}), [key]: out });
  return out;
}
const patternCache = new Map();
const pattern = source => { if (!patternCache.has(source)) patternCache.set(source, new RegExp(`^(?:${source})$`)); return patternCache.get(source); };
const BUILTIN = {
  '#string': () => true, '#anyURI': () => true,
  '#ID': value => /^[A-Za-z_][A-Za-z0-9._-]*$/.test(value),
  '#gYearMonth': value => /^-?[0-9]{4,}-(0[1-9]|1[0-2])(Z|[+-][0-9]{2}:[0-9]{2})?$/.test(value),
  '#base64Binary': value => /^[A-Za-z0-9+/\s]*={0,2}\s*$/.test(value),
};
/** null when the value follows the simple type, else the facet it breaks. */
export function simpleProblem(value, typeName) {
  if (typeName.startsWith('#')) return (BUILTIN[typeName] ?? (() => false))(value) ? null : 'format';
  const def = grammar.types[typeName];
  if (!def || def.c !== undefined) return 'format';
  const base = simpleProblem(value, def.b);
  if (base) return base;
  const length = [...value].length;
  if (def.l !== undefined && length !== def.l) return 'length';
  if (def.mn !== undefined && length < def.mn) return 'minLength';
  if (def.mx !== undefined && length > def.mx) return 'maxLength';
  if (def.e && !def.e.includes(value)) return 'enumeration';
  if (def.p && !def.p.some(source => pattern(source).test(value))) return 'pattern';
  if (def.mi !== undefined && value < def.mi) return 'minInclusive';
  return null;
}
/** The allowed values of an enumerated simple type (null when it is not one). */
export function enumerationOf(typeName) {
  for (let name = typeName; name && !name.startsWith('#');) { const def = grammar.types[name]; if (!def || def.c !== undefined) return null; if (def.e) return def.e; name = def.b; }
  return null;
}

// ---------------- validation ----------------
const children = node => Array.from(node.childNodes ?? []).filter(n => n.nodeType === 1);
function parse(xml) {
  if (typeof xml !== 'string' || !xml.length) throw new SchemaError('XML_INVALID');
  if (new TextEncoder().encode(xml).byteLength > SCHEMA_MAX_BYTES) throw new SchemaError('XML_TOO_LARGE');
  const body = xml.replace(/^\uFEFF/, '');
  // DTD, entities, comments, CDATA and processing instructions are refused; only the XML declaration may open the document.
  if (/<!/.test(body) || /<\?/.test(body.replace(/^<\?xml\s[^>]*\?>/, ''))) throw new SchemaError('XML_FORBIDDEN');
  if ((body.match(/</g) ?? []).length > 40000) throw new SchemaError('XML_TOO_LARGE');
  let doc;
  try { doc = new DOMParser({ onError: () => { throw new Error('parse'); } }).parseFromString(body, 'application/xml'); } catch { throw new SchemaError('XML_INVALID'); }
  if (!doc?.documentElement || doc.doctype) throw new SchemaError('XML_INVALID');
  let count = 0; const stack = [[doc.documentElement, 0]];
  while (stack.length) { const [node, depth] = stack.pop(); if (depth > 80 || ++count > 25000) throw new SchemaError('XML_TOO_LARGE'); for (const child of children(node)) stack.push([child, depth + 1]); }
  return doc.documentElement;
}
/**
 * The schema check of an NFe document. errors: [{ path, code, name?, expected?, facet? }] in document order, at most 100 (truncated says
 * there were more). code: missing (a required element), choice (one of `expected`), unexpected (an element out of place or unknown),
 * value (`facet` broken), attribute_missing, attribute_unexpected, attribute_value, text (text inside a group), namespace.
 */
export function checkNfeSchema(xml, { signature = 'optional' } = {}) {
  const unsigned = signature === 'optional', errors = [];
  let truncated = false;
  const report = error => { if (errors.length < MAX_ERRORS) errors.push(error); else truncated = true; };
  const root = parse(xml);
  if (root.localName !== 'NFe' || root.namespaceURI !== NFE_NS) { report({ path: `/${root.localName}`, code: 'unexpected', name: root.localName, expected: ['NFe'] }); return { valid: false, errors, truncated, profile: SCHEMA_PROFILE }; }
  const attributes = (node, def, path) => {
    const declared = new Map((def?.a ?? []).map(a => [a[0], a]));
    for (const attribute of Array.from(node.attributes ?? [])) {
      if (attribute.name === 'xmlns' || attribute.name.startsWith('xmlns:')) continue;
      const decl = attribute.namespaceURI ? null : declared.get(attribute.name);
      if (!decl) { report({ path: `${path}/@${attribute.name}`, code: 'attribute_unexpected', name: attribute.name }); continue; }
      const facet = simpleProblem(attribute.value, decl[1]);
      if (facet) report({ path: `${path}/@${attribute.name}`, code: 'attribute_value', name: attribute.name, facet });
    }
    for (const [name, , required] of declared.values()) if (required && !node.hasAttribute(name)) report({ path: `${path}/@${name}`, code: 'attribute_missing', name });
  };
  const element = (node, typeName, path) => {
    if (typeName === '#sig') return;
    const def = grammar.types[typeName];
    if (typeName.startsWith('#') || def?.c === undefined) {
      attributes(node, null, path);
      if (children(node).length) { report({ path, code: 'unexpected', name: children(node)[0].localName }); return; }
      const facet = simpleProblem(node.textContent ?? '', typeName);
      if (facet) report({ path, code: 'value', facet, expected: facet === 'enumeration' ? enumerationOf(typeName) ?? undefined : undefined });
      return;
    }
    attributes(node, def, path);
    if (Array.from(node.childNodes ?? []).some(n => (n.nodeType === 3 || n.nodeType === 4) && n.data.trim())) report({ path, code: 'text' });
    const kids = children(node).map(n => ({ node: n, name: n.localName, ns: n.namespaceURI }));
    const counts = new Map();
    const named = kids.map(kid => { const n = (counts.get(kid.name) ?? 0) + 1; counts.set(kid.name, n); return n; });
    const total = new Map(counts);
    const ctx = { assigned: [], failed: false };
    const fail = (code, at, extra) => { if (ctx.failed) return; ctx.failed = true; report({ path, code, ...(at < kids.length ? { before: kids[at].name } : {}), ...extra }); };
    const consume = (p, i) => {
      if (ctx.failed) return i;
      if (p[0] === 'e') {
        const [, name, type, min, max] = p, minimum = unsigned && type === '#sig' ? 0 : min;
        let n = 0;
        while ((max < 0 || n < max) && i < kids.length && kids[i].name === name) {
          const ns = type === '#sig' ? DS : NFE_NS;
          if (kids[i].ns !== ns) { fail('namespace', i, { name }); return i; }
          ctx.assigned.push([i, type]); i++; n++;
        }
        if (n < minimum) fail('missing', i, { name });
        return i;
      }
      const [k, min, max, items] = p;
      let r = 0;
      while (max < 0 || r < max) {
        const next = kids[i]?.name, f = first(p, unsigned);
        if (r >= min && (next === undefined || !f.names.has(next))) break;
        const start = i;
        if (k === 's') for (const item of items) { i = consume(item, i); if (ctx.failed) return i; }
        else {
          const alt = items.find(item => next !== undefined && first(item, unsigned).names.has(next)) ?? (r < min ? items.find(item => first(item, unsigned).nullable) : undefined);
          if (!alt) { fail('choice', i, { expected: [...f.names] }); return i; }
          i = consume(alt, i); if (ctx.failed) return i;
        }
        r++;
        if (i === start) break;
      }
      return i;
    };
    const end = def.c ? consume(def.c, 0) : 0;
    if (!ctx.failed && end < kids.length) report({ path, code: 'unexpected', name: kids[end].name });
    for (const [index, type] of ctx.assigned) {
      const kid = kids[index], suffix = total.get(kid.name) > 1 ? `[${named[index]}]` : '';
      element(kid.node, type, `${path}/${kid.name}${suffix}`);
    }
  };
  element(root, grammar.elements.NFe, '/NFe');
  // xs:unique pk_nItem of the layout: the nItem of every det of infNFe is distinct.
  const inf = children(root).find(n => n.localName === 'infNFe' && n.namespaceURI === NFE_NS), seen = new Set();
  for (const det of inf ? children(inf).filter(n => n.localName === 'det') : []) {
    const item = det.getAttribute('nItem');
    if (seen.has(item)) report({ path: `/NFe/infNFe/det[@nItem=${item}]`, code: 'unique', name: 'nItem' });
    seen.add(item);
  }
  return { valid: errors.length === 0, errors, truncated, profile: SCHEMA_PROFILE };
}

// ---------------- writing in the order of the layout ----------------
const escape = value => String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;').replaceAll("'", '&apos;');
const present = value => value !== null && value !== undefined && !(Array.isArray(value) && !value.length);
const namesOf = (p, out = new Set()) => { if (p[0] === 'e') out.add(p[1]); else p[3].forEach(item => namesOf(item, out)); return out; };
/**
 * Writes `name` of `typeName` from a plain tree: an object for a group (keys are element names, '@x' are attributes, arrays repeat the
 * element), a string for a value. The order comes from the layout; a key the layout does not have throws (a generator bug, never data).
 */
function write(name, typeName, value, path) {
  const def = grammar.types[typeName];
  if (typeName.startsWith('#') || def?.c === undefined) {
    if (typeof value !== 'string') throw new SchemaError(`SCHEMA_WRITE_VALUE:${path}`);
    return `<${name}>${escape(value)}</${name}>`;
  }
  if (!value || typeof value !== 'object' || Array.isArray(value)) throw new SchemaError(`SCHEMA_WRITE_GROUP:${path}`);
  const attrs = Object.keys(value).filter(k => k.startsWith('@'));
  for (const key of attrs) if (!def.a.some(a => a[0] === key.slice(1))) throw new SchemaError(`SCHEMA_WRITE_ATTRIBUTE:${path}/${key}`);
  const used = new Set();
  const walk = p => {
    if (p[0] === 'e') {
      const key = p[1];
      if (used.has(key) || !present(value[key])) return '';
      used.add(key);
      const list = Array.isArray(value[key]) ? value[key] : [value[key]];
      return list.map((item, i) => write(key, p[2], item, `${path}/${key}${list.length > 1 ? `[${i + 1}]` : ''}`)).join('');
    }
    if (p[0] === 's') return p[3].map(walk).join('');
    // A choice writes the alternative that has the keys of the tree (several alternatives may share a name, like IPI).
    const keys = Object.keys(value).filter(k => !k.startsWith('@') && !used.has(k) && present(value[k]));
    const alternative = p[3].map(item => [item, [...namesOf(item)].filter(n => keys.includes(n)).length]).sort((a, b) => b[1] - a[1])[0];
    return alternative && alternative[1] > 0 ? walk(alternative[0]) : '';
  };
  const body = def.c ? walk(def.c) : '';
  for (const key of Object.keys(value)) if (!key.startsWith('@') && present(value[key]) && !used.has(key)) throw new SchemaError(`SCHEMA_WRITE_UNKNOWN:${path}/${key}`);
  const attributeText = attrs.filter(k => present(value[k])).map(k => ` ${k.slice(1)}="${escape(value[k])}"`).join('');
  return `<${name}${name === 'NFe' ? ` xmlns="${NFE_NS}"` : ''}${attributeText}>${body}</${name}>`;
}
/** The NFe element of the tree { infNFe, infNFeSupl? } (no signature), in the order of the layout. */
export const schemaXml = tree => write('NFe', grammar.elements.NFe, tree, '/NFe');

// ---------------- messages ----------------
const FACETS = { pattern: 'o formato', enumeration: 'os valores permitidos', length: 'o tamanho exato', minLength: 'o tamanho mínimo', maxLength: 'o tamanho máximo', minInclusive: 'o valor mínimo', format: 'o formato' };
/** pt-BR text of one schema error, with the path of the layout. */
export function schemaErrorText(error) {
  switch (error.code) {
    case 'missing': return `Falta o campo ${error.name} em ${error.path}${error.before ? ` (antes de ${error.before})` : ''}.`;
    case 'choice': return `Falta um destes campos em ${error.path}: ${(error.expected ?? []).join(', ')}.`;
    case 'unexpected': return `O campo ${error.name} não é esperado nesta posição de ${error.path}.`;
    case 'value': return `O valor de ${error.path} não segue ${FACETS[error.facet] ?? 'o formato'} do leiaute${error.expected?.length && error.expected.length <= 12 ? ` (${error.expected.join(', ')})` : ''}.`;
    case 'attribute_missing': return `Falta o atributo ${error.name} em ${error.path.replace(/\/@[^/]+$/, '')}.`;
    case 'attribute_unexpected': return `O atributo ${error.name} não existe em ${error.path.replace(/\/@[^/]+$/, '')}.`;
    case 'attribute_value': return `O atributo ${error.path} não segue ${FACETS[error.facet] ?? 'o formato'} do leiaute.`;
    case 'namespace': return `O campo ${error.name} de ${error.path} não está no namespace da NF-e.`;
    case 'text': return `Há texto solto dentro do grupo ${error.path}.`;
    case 'unique': return `O número do item (nItem) se repete em ${error.path}.`;
    default: return `O XML não segue o leiaute em ${error.path}.`;
  }
}
