/** Expected [from,to] of a preset in the business date (São Paulo); the custom range is the request itself. */
export function homePeriodRange(key,businessDate,from=null,to=null){
  if(key==='hoje')return [businessDate,businessDate];
  if(key==='7d')return [addDays(businessDate,-6),businessDate];
  if(key==='30d')return [addDays(businessDate,-29),businessDate];
  // 3M, 6M and 12M start on the first day of the month (the SQL of migration 152 does the same).
  if(key==='3m')return [`${addMonths(businessDate.slice(0,7),-2)}-01`,businessDate];
  if(key==='6m')return [`${addMonths(businessDate.slice(0,7),-5)}-01`,businessDate];
  if(key==='12m')return [`${addMonths(businessDate.slice(0,7),-11)}-01`,businessDate];
  return [from,to];
}
/** Chart buckets: one per day up to 62 days, otherwise one per calendar month (end months may be partial). */
export function homePeriodBuckets(from,to){
  const days=dayCount(from,to);
  if(days<=62)return {grain:'day',buckets:Array.from({length:days},(_,index)=>addDays(from,index))};
  const buckets=[];for(let month=from.slice(0,7);month<=to.slice(0,7);month=addMonths(month,1))buckets.push(month);
  return {grain:'month',buckets};
}

